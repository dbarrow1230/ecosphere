import mongoose from "mongoose";
const list=value=>Array.isArray(value)?value:value==null?[]:[value];
const text=value=>{
 if(value==null)return '';
 if(Array.isArray(value))return value.map(text).filter(Boolean).join('; ');
 if(typeof value==='object')return text(value.note??value.name??value.title??value.description);
 const result=String(value).trim();
 return /^[a-f0-9]{24}$/i.test(result)||/^REPLACE_WITH_/i.test(result)?'':result;
};
export const legacyJournalDate=record=>{
 const value=record.journal_date??record.JournalDate;
 if(!value)return null;
 const result=new Date(value);
 return Number.isNaN(result.getTime())?null:result;
};

export function legacyJournalFields(record,context={}){
 const notes=list(record.notes).filter(note=>note!=null).map(note=>typeof note==='string'?{note,date:legacyJournalDate(record)}:{...note,date:note.date||note.note_date||legacyJournalDate(record)});
 const originalText=text(record.Notes);
 const noteText=text(record.notes);
 const lines=[];
 const add=(label,value)=>{const content=text(value);if(content)lines.push(label?`${label}: ${content}`:content);};
 add('',originalText);
 add('Growth progress',record.stage_progress);
 add('Notes',noteText);
 add('Actions taken',record.actionsTaken);
 add('Fertilizer notes',record.fertilizer_notes);
 add('Growth stage',record.growth_stage);
 add('Growing medium',record.medium);
 if(record.is_indoor!==undefined&&record.is_indoor!==null)add('Indoors',record.is_indoor?'Yes':'No');
 const height=record.growth_height||{};
 add('Height',[height.inches!=null?`${height.inches} in`:'',height.cm!=null?`${height.cm} cm`:''].filter(Boolean).join(' / '));
 if(record.expected_germination)add('Expected germination',String(record.expected_germination instanceof Date?record.expected_germination.toISOString():record.expected_germination).slice(0,10));
 add('Nutrients',record.nutrients??record.Nutrients);
 add('pH',record.phLevel);
 const temperature=record.weather?.temperature||{};
 add('Temperature',[temperature.fahrenheit!=null?`${temperature.fahrenheit} °F`:'',temperature.celsius!=null?`${temperature.celsius} °C`:''].filter(Boolean).join(' / '));
 if(record.weather?.humidity!=null)add('Humidity',`${record.weather.humidity}%`);
 if(record.weather?.rain!=null)add('Rain',record.weather.rain);
 add('Pests observed',record.pestsObserved);
 add('Plant issues',record.plantIssues);
 for(const [key,label] of Object.entries({location:'Location',soil:'Soil',watering:'Watering schedule',lighting:'Lighting',container:'Container'}))add(label,context[key]);
 const heading=text(record.title)||[context.sourceName,text(record.growth_stage)].filter(Boolean).join(' · ')||(originalText||noteText||text(record.stage_progress)).split(/\r?\n/)[0].slice(0,90)||'Garden journal';
 return {
  title:heading,
  entry:lines.join('\n'),
  entryDate:legacyJournalDate(record),
  notes,
  images:list(record.photos).map(photo=>photo?.file_path||photo?.url||photo?.filename).filter(Boolean)
 };
}

// Recognize the exact fields generated by the earlier incomplete converter.
// A differing timestamp, body, title, date, link, image or note means the copy
// may have been edited and must not be overwritten by automatic repair.
export function repairableLegacyJournalCopy(source,current,previousFields){
 if(!current||current.legacyJournalMappingVersion>=3)return false;
 const same=(a,b)=>JSON.stringify(a??null)===JSON.stringify(b??null);
 if(current.legacyJournalMappingVersion===2){
  return !!previousFields&&['title','entry','entryDate','notes','images'].every(key=>same(current[key],previousFields[key]))&&same(current.updatedAt,source.updatedAt)&&same(current.createdAt,source.createdAt)&&same(current.planting,source.plant_instance_id||null);
 }
 const previousEntry=[source.stage_progress,...list(source.actionsTaken),...list(source.fertilizer_notes),source.notes?.note].filter(Boolean).join('\n');
 const previousTitle=source.title||source.growth_stage||'Garden journal';
 const oldNotes=list(source.notes).map(note=>typeof note==='string'?{note}:({note:note.note||'',date:note.note_date?new Date(note.note_date):null}));
 return current.title===previousTitle&&current.entry===previousEntry&&same(current.entryDate,source.journal_date?new Date(source.journal_date):null)&&same(current.updatedAt,source.updatedAt)&&same(current.createdAt,source.createdAt)&&same(current.planting,source.plant_instance_id||null)&&same(current.images,list(source.photos).map(photo=>photo.file_path).filter(Boolean))&&(same(current.notes,source.notes)||same(current.notes,oldNotes));
}

export async function repairLegacyJournalCopies(db){
 const references={};
 for(const [key,collection] of Object.entries({soil:'plant_soil',watering:'plant_waterings',lighting:'plant_lighting',container:'plant_containers',location:'locations'})){
  references[key]=new Map();
  for await(const row of db.collection(collection).find({}))references[key].set(String(row._id),text(row.name||row.location_name||row.soil||row.habit||row.lightingtype||row.container_type||row.container_name||row.containertype));
 }
 let repaired=0,edited=0;
 for await(const source of db.collection('plant_journals').find({})){
  const current=await db.collection('journal_entries').findOne({_id:source._id});
  if(!current||current.legacyJournalMappingVersion>=3)continue;
  const context={};
  for(const [key,sourceKey] of Object.entries({soil:'soil_type',watering:'watering_schedule',lighting:'lighting_id',container:'container_id',location:'location_id'}))context[key]=references[key].get(String(source[sourceKey]));
  if(source.plant_instance_id){
   const plantingId=/^[a-f0-9]{24}$/i.test(String(source.plant_instance_id))?new mongoose.Types.ObjectId(String(source.plant_instance_id)):source.plant_instance_id;
   const planting=await db.collection('plantings').findOne({_id:plantingId});
   context.sourceName=planting?.sourceName||planting?.instanceName||'';
  }
  const priorFields=legacyJournalFields(source,{...context,container:undefined});
  if(!repairableLegacyJournalCopy(source,current,priorFields)){edited++;continue;}
  const fields=legacyJournalFields(source,context);
  const query={_id:current._id,title:current.title,entry:current.entry,entryDate:current.entryDate,updatedAt:current.updatedAt===undefined?{$exists:false}:current.updatedAt};
  if(current.notes!==undefined)query.notes=current.notes;
  const result=await db.collection('journal_entries').updateOne(query,{$set:{...fields,legacyJournalMappingVersion:3}});
  repaired+=result.modifiedCount||0;
 }
 return {repaired,edited};
}
